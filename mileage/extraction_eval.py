"""Extraction-accuracy eval harness (Cursor-Mileage-Plan.md §6.3).

Scores any `LLMExtractor` backend (deterministic today; `OllamaExtractor`
once a local model is actually running) against hand-labeled fixtures in
`tests/fixtures/extraction/`:

  - row-level precision/recall (did it find the right (program, region_a,
    region_b, cabin, miles) rows, no more, no fewer)
  - a hallucination count — produced rows whose `miles` is NOT literally
    present in the source document. This should always be 0 for any
    compliant extractor (the grounding guard already lives inside
    `DeterministicExtractor`/`OllamaExtractor` before a row is ever
    returned), so a non-zero count here is a regression in that guard, not
    a "the model is bad" signal — treat it as a hard CI failure.

Run: `python -m mileage.extraction_eval` (deterministic backend, default) or
`python -m mileage.extraction_eval --backend ollama` once Ollama is running.

IMPORTANT: the 26 fixtures shipped in tests/fixtures/extraction/ are all
synthetic (hand-written or generated by _generate_bootstrap_set.py) — they are
NOT the 20-30 real, hand-labeled newsletter/blog fixtures the plan calls for.
As of 2026-07-08 the deterministic backend scores precision=0.68 recall=0.61
against this synthetic set, with every gap's root cause documented in that
fixture's "notes" field. Treat that as "here's a measured baseline and a set
of diagnosed gaps to beat," not "the extractor is production-ready." See
Cursor-LLM-Extractor-Task.md for what comes next (real fixtures from the
actual inbox/blogs, then compare backends on those).
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, List

from .providers.aggregator.extract.base import LLMExtractor
from .providers.aggregator.extract.grounding import number_is_grounded

_DEFAULT_FIXTURES_DIR = (
    Path(__file__).resolve().parent.parent / "tests" / "fixtures" / "extraction"
)

# Mirrors tests/fixtures/extraction/schema.json. Kept as plain-Python checks
# (no `jsonschema` dependency) so a malformed fixture fails loudly and early
# rather than silently scoring 0/0 somewhere in the middle of a 20-30-fixture
# run — a fixture with a typo'd program/region/cabin token, or an
# expected_rows entry whose own miles isn't grounded in its own document, is a
# broken fixture, not a hard test case, and should never be scored as one.
_VALID_PROGRAMS = {"aeroplan", "turkish", "lifemiles", "krisflyer", "ana", "eva"}
_VALID_REGIONS = {
    "north_america", "europe", "north_asia", "southeast_asia", "south_asia",
    "middle_east", "oceania", "south_america", "africa",
}
_VALID_CABINS = {"economy", "premium_economy", "business", "first"}


def validate_fixture(doc: dict, name: str) -> List[str]:
    """Return a list of schema-violation error strings (empty = valid)."""
    errors: List[str] = []
    if not isinstance(doc.get("document"), str) or not doc["document"].strip():
        errors.append("'document' must be a non-empty string")
    if not isinstance(doc.get("source_hint", ""), str):
        errors.append("'source_hint' must be a string")
    rows = doc.get("expected_rows")
    if not isinstance(rows, list):
        errors.append("'expected_rows' must be a list (use [] for none expected)")
        rows = []
    document = doc.get("document", "")
    for i, row in enumerate(rows):
        prefix = f"expected_rows[{i}]"
        if not isinstance(row, dict):
            errors.append(f"{prefix} must be an object")
            continue
        program = row.get("program")
        if program not in _VALID_PROGRAMS:
            errors.append(f"{prefix}.program={program!r} not in {sorted(_VALID_PROGRAMS)}")
        for field_name in ("region_a", "region_b"):
            val = row.get(field_name)
            if val not in _VALID_REGIONS:
                errors.append(
                    f"{prefix}.{field_name}={val!r} not a canonical region token "
                    f"(got prose? region_a/region_b must already be canonicalized)"
                )
        cabin = row.get("cabin")
        if cabin not in _VALID_CABINS:
            errors.append(f"{prefix}.cabin={cabin!r} not in {sorted(_VALID_CABINS)}")
        miles = row.get("miles")
        if not isinstance(miles, int) or isinstance(miles, bool) or miles <= 0:
            errors.append(f"{prefix}.miles={miles!r} must be a positive integer")
        elif not number_is_grounded(miles, document):
            errors.append(
                f"{prefix}.miles={miles} does not literally appear in this fixture's "
                f"own 'document' — the fixture itself is broken, fix the number or the text"
            )
    if errors:
        errors = [f"{name}: {e}" for e in errors]
    return errors


@dataclass
class FixtureResult:
    name: str
    expected: int
    produced: int
    matched: int
    ungrounded: int
    missed: List[dict] = field(default_factory=list)
    extra: List[dict] = field(default_factory=list)


@dataclass
class ExtractionEvalReport:
    backend: str
    results: List[FixtureResult] = field(default_factory=list)
    fixture_errors: List[str] = field(default_factory=list)

    @property
    def total_expected(self) -> int:
        return sum(r.expected for r in self.results)

    @property
    def total_produced(self) -> int:
        return sum(r.produced for r in self.results)

    @property
    def total_matched(self) -> int:
        return sum(r.matched for r in self.results)

    @property
    def precision(self) -> float:
        return self.total_matched / self.total_produced if self.total_produced else 1.0

    @property
    def recall(self) -> float:
        return self.total_matched / self.total_expected if self.total_expected else 1.0

    @property
    def hallucinations(self) -> int:
        return sum(r.ungrounded for r in self.results)

    def print_report(self) -> None:
        print(f"Extraction eval - backend={self.backend}")
        if self.fixture_errors:
            print("INVALID FIXTURES (skipped, not scored):")
            for e in self.fixture_errors:
                print(f"  {e}")
        for r in self.results:
            print(
                f"  {r.name}: expected={r.expected} produced={r.produced} "
                f"matched={r.matched} ungrounded={r.ungrounded}"
            )
            for m in r.missed:
                print(f"    MISSED: {m}")
            for e in r.extra:
                print(f"    EXTRA:  {e}")
        print(
            f"TOTAL precision={self.precision:.2f} recall={self.recall:.2f} "
            f"hallucinations={self.hallucinations} "
            f"(fixtures={len(self.results)} - see tests/fixtures/extraction/README.md)"
        )


def _expected_key(row: dict) -> tuple:
    return (row["program"], row["region_a"], row["region_b"], row["cabin"], row["miles"])


def _chartrow_key(row: Any) -> tuple:
    return (row.program, row.region_a, row.region_b, row.cabin, row.miles)


def _chartrow_dict(row: Any) -> dict:
    return {
        "program": row.program,
        "region_a": row.region_a,
        "region_b": row.region_b,
        "cabin": row.cabin,
        "miles": row.miles,
    }


def run_extraction_eval(
    extractor: LLMExtractor, fixtures_dir: Path = _DEFAULT_FIXTURES_DIR
) -> ExtractionEvalReport:
    """Run `extractor` against every fixture and score row-level accuracy."""
    backend_name = getattr(extractor, "name", type(extractor).__name__)
    report = ExtractionEvalReport(backend=backend_name)

    for path in sorted(fixtures_dir.glob("*.json")):
        if path.name == "schema.json":
            continue  # the schema definition itself, not a fixture
        doc = json.loads(path.read_text(encoding="utf-8"))
        errors = validate_fixture(doc, path.stem)
        if errors:
            report.fixture_errors.extend(errors)
            continue

        document = doc["document"]
        hint = doc.get("source_hint", "")
        expected_rows = doc.get("expected_rows", [])

        produced_rows = extractor.extract(document, source_hint=hint)

        expected_keys = {_expected_key(r) for r in expected_rows}
        produced_keys = [_chartrow_key(r) for r in produced_rows]
        matched = sum(1 for k in produced_keys if k in expected_keys)
        ungrounded = sum(
            1 for r in produced_rows if not number_is_grounded(r.miles, document)
        )
        found_keys = set(produced_keys)
        missed = [r for r in expected_rows if _expected_key(r) not in found_keys]
        extra = [
            _chartrow_dict(r)
            for r, k in zip(produced_rows, produced_keys)
            if k not in expected_keys
        ]

        report.results.append(
            FixtureResult(
                name=path.stem,
                expected=len(expected_rows),
                produced=len(produced_rows),
                matched=matched,
                ungrounded=ungrounded,
                missed=missed,
                extra=extra,
            )
        )
    return report


def main() -> int:
    import argparse

    from .config import Config
    from .providers.aggregator.extract import build_extractor

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--backend",
        default=None,
        help="deterministic|ollama (default: $MILEAGE_EXTRACTOR_BACKEND or deterministic)",
    )
    parser.add_argument(
        "--fixtures-dir",
        default=None,
        help="override the fixtures directory (default: tests/fixtures/extraction)",
    )
    args = parser.parse_args()

    config = Config.from_env()
    if args.backend:
        config.extractor_backend = args.backend
    extractor = build_extractor(config)

    fixtures_dir = Path(args.fixtures_dir) if args.fixtures_dir else _DEFAULT_FIXTURES_DIR
    report = run_extraction_eval(extractor, fixtures_dir)
    report.print_report()

    if report.fixture_errors:
        print("FAIL: one or more fixtures are malformed (see INVALID FIXTURES above).")
        return 1
    if report.hallucinations:
        print("FAIL: the grounding guard let an ungrounded number through.")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
